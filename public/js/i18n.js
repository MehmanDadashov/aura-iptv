  function detect() {
    var saved = null;
    try { saved = localStorage.getItem('aura-lang'); } catch (e) {}
    if (saved && saved !== 'auto' && D[saved]) return saved;
    var prefs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || 'en'];
    for (var i = 0; i < prefs.length; i++) {
      var code = String(prefs[i]).toLowerCase().split('-')[0];
      if (D[code]) return code;
    }
    return 'en';
  }

  var current = detect();

  function t(key, vars) {
    var s = (D[current] && D[current][key]) || D.en[key] || key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    root.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    root.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var s = t(el.getAttribute('data-i18n-aria'));
      el.setAttribute('aria-label', s);
      el.setAttribute('title', s);
    });
    document.documentElement.lang = current;
    document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
  }

  function setLang(code) {
    try { localStorage.setItem('aura-lang', code); } catch (e) {}
    current = code === 'auto' ? detect() : (D[code] ? code : 'en');
    if (code === 'auto') { try { localStorage.setItem('aura-lang', 'auto'); } catch (e) {} }
    apply();
    document.dispatchEvent(new CustomEvent('aura:lang', { detail: { lang: current } }));
  }

  window.AuraI18n = {
    t: t, apply: apply, setLang: setLang, detect: detect,
    lang: function () { return current; },
    langs: LANGS, dicts: D
  };
